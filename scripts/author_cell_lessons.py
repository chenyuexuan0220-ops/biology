def build():
    lessons = []
    for sequence, topic in enumerate(TOPICS, 1):
        for tier, low, high, label in TIERS:
            material = topic[tier]
            checks = []
            for i, line in enumerate(material["questions"]):
                stem, a, b, c, d, answer, explanation = line.split("|")
                checks.append(
                    {
                        "id": f"q{i + 1}",
                        "stem": stem,
                        "options": dict(zip("ABCD", [a, b, c, d])),
                        "answer": answer,
                        "explanation": explanation,
                        "cognitive_level": min(
                            4, (0 if tier == "INTRO" else 2 if tier == "APPLICATION" else 3) + i % 2
                        ),
                        "competency_code": "KNOWLEDGE_UNDERSTANDING" if i < 2 else "MECHANISM_REASONING",
                        "revisit_section": f"s{min(3, i + 1)}",
                        "prerequisite_code": None,
                        "evidence_kind": "TRANSFER" if tier == "COMPETITION" and i == 3 else "STANDARD",
                    }
                )
            if topic.get("prior"):
                parent = TOPICS[sequence - 2]
                # A distinct prerequisite probe uses the previous concept's central misconception.
                stem, a, b, c, d, answer, explanation = parent[tier]["questions"][1].split("|")
                checks.append(
                    {
                        "id": "prerequisite",
                        "stem": "前置概念核对：" + stem,
                        "options": dict(zip("ABCD", [a, b, c, d])),
                        "answer": answer,
                        "explanation": explanation,
                        "cognitive_level": 1 if tier == "INTRO" else 2 if tier == "APPLICATION" else 3,
                        "competency_code": "KNOWLEDGE_UNDERSTANDING",
                        "revisit_section": "s1",
                        "prerequisite_code": topic["prior"],
                        "evidence_kind": "STANDARD",
                    }
                )
            document = {
                "title": f"{topic['name']}：{label}",
                "summary": f"围绕{topic['name']}，通过结构图、例题和检测，完成从概念到证据的{label}学习。",
                "objectives": material["objectives"],
                "estimated_minutes": 20 if tier == "INTRO" else 30 if tier == "APPLICATION" else 40,
                "prerequisites": [topic["prior"]] if topic.get("prior") else [],
                "sections": [
                    {"id": f"s{i + 1}", "title": title, "text": text}
                    for i, (title, text) in enumerate(material["sections"])
                ],
                "diagram": {"kind": topic["diagram"], "labels": topic["labels"], "caption": topic["caption"]},
                "examples": [{"prompt": material["example"][0], "reasoning": material["example"][1]}],
                "misconceptions": [{"claim": a, "correction": b} for a, b in topic["misconceptions"]],
                "checks": checks,
                "pass_ratio": 0.8,
                "adaptations": {
                    "junior": f"先用身边可观察的例子描述{topic['name']}，再对照图示把结构、现象和解释连起来。遇到公式先说清每个量的意思，按步骤推理。",
                    "senior": f"围绕{topic['name']}明确变量、驱动力和模型边界；区分事实与机制解释，写出每个结论成立的条件，并设计能区分不同解释的证据。",
                },
                "sources": [
                    "OpenStax Biology 2e，第 4 章 Cell Structure、第 5 章 Structure and Function of Plasma Membranes；https://openstax.org/details/books/biology-2e",
                    "本项目原创分层讲解与检测；待人工核对，非官方竞赛试题。",
                ],
            }
            lessons.append(
                {
                    "code": f"cell-transport:{topic['code']}:{tier}",
                    "unit_code": "cell-transport",
                    "unit_title": "细胞与物质运输",
                    "sequence": sequence,
                    "knowledge_code": topic["code"],
                    "tier": tier,
                    "min_level": low,
                    "max_level": high,
                    "version": 1,
                    "document": document,
                }
            )
    output = ROOT / "seed/lessons/cell_transport.yaml"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(yaml.safe_dump(lessons, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(
        f"Authored {len(lessons)} lesson drafts; {sum(len(lesson['document']['checks']) for lesson in lessons)} checks. Nothing published."
    )


